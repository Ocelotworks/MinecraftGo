package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// packetReport is the generator's packets.json: state -> flow -> packet name ->
// the id that packet travels under.
//
// Ids are handed out per state and flow in alphabetical order of the packet's
// registry name, so adding a single packet renumbers every packet after it.
// That is why these are generated rather than transcribed.
type packetReport map[string]map[string]map[string]struct {
	ProtocolID int `json:"protocol_id"`
}

// packetSection is one state/flow pair and the constant naming it uses.
//
// Names are suffixed by state because the same packet name appears in more than
// one of them — keep_alive, disconnect and custom_payload all exist in both
// configuration and play, under different ids.
type packetSection struct {
	state   string
	flow    string
	prefix  string
	suffix  string
	comment string
}

var packetSections = []packetSection{
	{"login", "clientbound", "CB", "Login", "LOGIN, clientbound"},
	{"login", "serverbound", "SB", "Login", "LOGIN, serverbound"},
	{"configuration", "clientbound", "CB", "Configuration", "CONFIGURATION, clientbound"},
	{"configuration", "serverbound", "SB", "Configuration", "CONFIGURATION, serverbound"},
	{"play", "clientbound", "CB", "", "PLAY, clientbound"},
	{"play", "serverbound", "SB", "", "PLAY, serverbound"},
}

// generatePackets writes the packet id constants from the generator's report.
func generatePackets(reportsDir string, outputPath string) error {
	report := packetReport{}
	if err := readJSONFile(filepath.Join(reportsDir, "packets.json"), &report); err != nil {
		return err
	}

	var source strings.Builder
	source.WriteString("package constants\n\n// Code generated by cmd/mcdata. DO NOT EDIT.\n//\n")
	source.WriteString("// Packet ids are assigned per state and flow in alphabetical order of the\n")
	source.WriteString("// packet's registry name, so one new packet renumbers everything after it.\n")

	total := 0
	for _, section := range packetSections {
		packets := report[section.state][section.flow]
		if len(packets) == 0 {
			return fmt.Errorf("packets.json has no %s/%s packets", section.state, section.flow)
		}

		names := make([]string, 0, len(packets))
		for name := range packets {
			names = append(names, name)
		}
		sort.Slice(names, func(i, j int) bool {
			return packets[names[i]].ProtocolID < packets[names[j]].ProtocolID
		})

		seen := make(map[string]string, len(names))
		lines := make([][2]string, 0, len(names))
		width := 0

		for _, name := range names {
			constant := section.prefix + packetConstantName(name, section.suffix)
			if previous, clash := seen[constant]; clash {
				return fmt.Errorf("%s and %s both map to %s", previous, name, constant)
			}
			seen[constant] = name

			if len(constant) > width {
				width = len(constant)
			}
			lines = append(lines, [2]string{constant, fmt.Sprintf("0x%02X", packets[name].ProtocolID)})
		}

		fmt.Fprintf(&source, "\n// %s\nconst (\n", section.comment)
		for _, line := range lines {
			fmt.Fprintf(&source, "\t%-*s = %s\n", width, line[0], line[1])
		}
		source.WriteString(")\n")
		total += len(lines)
	}

	target := filepath.Join(outputPath, "constants", "Packets.go")
	if err := os.WriteFile(target, []byte(source.String()), 0o644); err != nil {
		return fmt.Errorf("writing %s: %w", target, err)
	}
	fmt.Printf("Wrote %s: %d packet ids\n", target, total)

	return nil
}

// packetConstantName turns a registry name such as "minecraft:debug/block_value"
// into the Go identifier fragment "DebugBlockValue", tagged with the state it
// belongs to.
//
// The tag is what keeps the states apart, so it is only left off when the name
// already carries it — "finish_configuration" would otherwise come out as
// FinishConfigurationConfiguration.
func packetConstantName(name string, stateSuffix string) string {
	name = strings.TrimPrefix(name, "minecraft:")

	var out strings.Builder
	for _, word := range strings.FieldsFunc(name, func(r rune) bool { return r == '_' || r == '/' }) {
		out.WriteString(strings.ToUpper(word[:1]))
		out.WriteString(word[1:])
	}

	constant := out.String()
	if strings.Contains(constant, stateSuffix) {
		return constant
	}
	return constant + stateSuffix
}
